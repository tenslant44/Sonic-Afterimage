const cache = {};
function atlas(style, outline) {
  const key = style + '|' + outline;
  if (cache[key]) return cache[key];
  const rows = STYLES[style] || STYLES.white;
  const c = document.createElement('canvas');
  c.width = CHARS.length * CW; c.height = CH;
  const g = c.getContext('2d');
  CHARS.forEach((ch, i) => {
    const glyph = G[ch];
    const ox = i * CW + 1 - 1, oy = 1;
    if (outline) {
      g.fillStyle = outline;
      for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (glyph[y][x] === '1') {
        g.fillRect(ox + x - 1 + 1, oy + y - 1, 3, 3);
      }
    }
    for (let y = 0; y < 7; y++) {
      g.fillStyle = rows[y];
      for (let x = 0; x < 5; x++) if (glyph[y][x] === '1') g.fillRect(ox + x + 1, oy + y, 1, 1);
    }
  });
  cache[key] = c;
  return c;
}

export function textWidth(str, scale = 1, spacing = 0) {
  return str.length * (CW + spacing) * scale;
}

export function drawText(ctx, str, x, y, opts = {}) {
  const { style = 'white', scale = 1, align = 'left', outline = '#000', spacing = 0, italic = 0 } = opts;
  str = String(str).toUpperCase();
  const a = atlas(style, outline);
  const w = textWidth(str, scale, spacing);
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  for (let i = 0; i < str.length; i++) {
    let idx = CHARS.indexOf(str[i]);
    if (idx < 0) idx = CHARS.indexOf(' ');
    const dx = x + i * (CW + spacing) * scale;
    if (italic) {
      // draw row slices shifted for an italic slant
      for (let r = 0; r < CH; r++) {
        const sh = Math.round((CH - r) * italic * 0.25) * scale;
        ctx.drawImage(a, idx * CW, r, CW, 1, dx + sh, y + r * scale, CW * scale, scale);
      }
    } else {
      ctx.drawImage(a, idx * CW, 0, CW, CH, dx, y, CW * scale, CH * scale);
    }
  }
  return w;
}

// Wrap text into lines that fit width (in pixels at scale 1)
export function wrap(str, maxW) {
  const words = str.split(' ');
  const lines = [];
  let cur = '';
  for (const w of words) {
    const t = cur ? cur + ' ' + w : w;
    if (textWidth(t) > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}
